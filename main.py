def _load_fonts():
    data = zlib.decompress(base64.b64decode("".join(GLYPH_BLOB.split())))
    assert data[:3] == b"NF3"
    pos = 3
    n = data[pos]
    pos += 1
    fonts = {}
    for key in FONT_KEYS[:n]:
        ascent, descent = data[pos], data[pos + 1]
        pos += 2
        ncs = data[pos]
        pos += 1
        charset = data[pos:pos + ncs].decode("utf-8")
        pos += ncs
        glyphs = {}
        for ch in charset:
            adv = data[pos]
            x0 = data[pos + 1] - 128
            y0 = data[pos + 2] - 128
            w, h = data[pos + 3], data[pos + 4]
            pos += 5
            bmp = bytes(data[pos:pos + w * h])
            pos += w * h
            glyphs[ch] = (adv, x0, y0, w, h, bmp)
        if " " not in glyphs:
            # B12's charset omits the space (digits + chip letters
            # only); synthesize a blank with the measured advance
            # (Liberation Sans Bold 12 space = 3px) so "14 " etc.
            # lay out exactly as in v6.
            glyphs[" "] = (3, 0, 0, 0, 0, b"")
        fonts[key] = (ascent, descent, glyphs)
    assert pos == len(data)
    return fonts


FONTS = _load_fonts()


def line_h(font):
    ascent, descent, _ = FONTS[font]
    return ascent + descent


